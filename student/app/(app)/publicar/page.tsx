import Link from 'next/link';
import { redirect } from 'next/navigation';
import { PostBuilder, type EditingPost } from '@/components/post-builder';
import { Button } from '@/components/ui/button';
import { getFeed } from '@/lib/feed';
import { getProfile } from '@/lib/me';
import type { BuiltKind } from '@/lib/post-blocks';

export const metadata = { title: 'Criar publicação · Kixi' };

const BUILT: readonly BuiltKind[] = ['doubt', 'topic', 'study_card', 'solution', 'challenge'];

/**
 * Um só sítio para todas as publicações: pergunta, dica, cartão, resolução ou desafio, com os blocos à mão. Sem turma não há onde publicar.
 *
 * Com `?editar=<id>` (#753) o mesmo construtor reabre uma publicação do próprio aluno. Só o autor
 * edita, e uma publicação de simulação ou automática não se edita: nesses casos volta-se ao início,
 * como se o endereço não existisse. Uma publicação que já não está na primeira página do feed não
 * se procura às cegas: diz-se que não foi possível abri-la, em vez de um redireccionamento mudo.
 */
export default async function PublicarPage({ searchParams }: { searchParams: Promise<Record<string, string | string[] | undefined>> }) {
  const query = await searchParams;
  const profile = await getProfile();
  const classId = profile.kind === 'ok' ? profile.me.currentClass?.id : undefined;
  if (!classId) redirect('/inicio');

  const raw = Array.isArray(query.editar) ? query.editar[0] : query.editar;
  const id = Number(raw);
  if (!raw || !Number.isInteger(id) || id <= 0) return <PostBuilder classId={classId} />;

  const feed = await getFeed(classId, 1, 50);
  const post = feed.ok ? feed.data.find((p) => p.id === id) : undefined;
  if (!post) {
    // O `getFeed` só lê a primeira página: uma publicação antiga pode existir e não estar aqui.
    // Sem esta mensagem, «Editar» num post antigo parecia um botão avariado.
    return (
      <section className="mx-auto grid w-full max-w-[560px] gap-3 px-4 py-10 text-center md:px-0">
        <h1 className="m-0 text-xl leading-tight font-extrabold">Não foi possível abrir esta publicação para editar</h1>
        <p className="m-0 text-sm text-muted-foreground">
          Ela pode já não existir ou estar mais adiante no feed. Volta ao início e abre-a a partir do cartão.
        </p>
        <Button asChild variant="outline" className="mx-auto">
          <Link href="/inicio">Voltar ao início</Link>
        </Button>
      </section>
    );
  }
  if (profile.kind !== 'ok' || post.authorAccountId !== profile.me.accountId) redirect('/inicio');
  if (post.isAutoGenerated || !(BUILT as readonly string[]).includes(post.type)) redirect('/inicio');

  const editing: EditingPost = {
    id: post.id,
    kind: post.type as BuiltKind,
    title: post.title,
    blocks: post.blocks ?? null,
    content: post.content,
  };
  return <PostBuilder classId={classId} editing={editing} />;
}
