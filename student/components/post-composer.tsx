'use client';

import { useState, useTransition } from 'react';
import { Alert } from '@/components/ui/alert';
import { UserAvatar } from '@/components/user-avatar';
import { Input } from '@/components/ui/input';
import { cn } from '@/lib/utils';
import { MIN_POST_LENGTH, MAX_POST_LENGTH, canPublish } from '@/lib/feed-rules';
import { publishPostAction } from '@/lib/feed-actions';
import { useMe } from '@/lib/me-context';
import { fullName, photoUrl } from '@/lib/profile';
import type { FeedPost } from '@/lib/feed';

const AJUDA_ID = 'composer-ajuda';

/** O compositor do telemóvel no topo do feed. O desenho é deliberadamente idêntico à pílula
 *  «Partilha uma dúvida ou uma dica…» do md+ — mesma cor, mesma borda, mesmo fundo, mesmo
 *  tamanho de avatar e de texto, e o mesmo círculo verde com «+» — mas no telemóvel com
 *  comportamento: o «+» publica aqui mesmo, sem navegar para /publicar. O cartão entra no
 *  feed imediatamente (via `onOptimistic`, síncrono) e cai para fora na falha pela via
 *  simétrica (`onOptimisticFailed`).
 *
 *  O placeholder menciona dica, mas o tipo é sempre `doubt`: o copy é do produto (vem da
 *  issue #796 e da pílula que já existe no md+), não uma escolha nossa. */
export function PostComposer({ classId, onOptimistic, onOptimisticFailed }: {
  classId: number;
  onOptimistic?: (post: FeedPost) => void;
  onOptimisticFailed?: (post: FeedPost) => void;
}) {
  const me = useMe();
  const [text, setText] = useState('');
  const [publishing, setPublishing] = useState(false);
  const [publishError, setPublishError] = useState<string | null>(null);
  const [, startTransition] = useTransition();

  const ready = canPublish(text) && !publishing;

  const publish = (e: React.FormEvent) => {
    e.preventDefault();
    if (!canPublish(text)) return;
    const sent = text.trim();
    setPublishing(true);
    setPublishError(null);
    setText(''); // o campo esvazia-se logo; se falhar, o texto volta

    // onOptimistic é síncrono de propósito: mantém a chamada do action síncrona com o clique,
    // e o cartão no topo emparelha com o «+» no mesmo tick.
    const optimisticPost = me ? {
      id: -Date.now(), authorAccountId: me.accountId, institutionId: 0, schoolYearId: 0, courseId: 0, classId,
      type: 'doubt', title: null, content: sent, isAutoGenerated: false, commentCount: 0, hasReacted: false,
      createdAt: new Date().toISOString(), updatedAt: new Date().toISOString(),
    } as FeedPost : null;
    if (optimisticPost) onOptimistic?.(optimisticPost);

    startTransition(async () => {
      // Uma falha (429/500/rede) não leva a página para o ecrã de erro; o texto volta ao campo.
      const result = await publishPostAction(classId, 'doubt', sent)
        .catch(() => ({ ok: false as const, message: 'Não foi possível publicar agora. O texto ficou no campo.' }));
      setPublishing(false);
      if (!result.ok) {
        if (optimisticPost) onOptimisticFailed?.(optimisticPost);
        setText(sent);
        setPublishError(result.message);
      }
    });
  };

  return (
    <>
      <form id="publicar" onSubmit={publish}
        className="flex items-center gap-3 rounded-full border border-[#e9ebe7] bg-white px-3.5 py-3 transition-shadow focus-within:ring-[3px] focus-within:ring-ring/40">
        <UserAvatar name={fullName(me)} src={photoUrl(me)} size={44} />
        <Input
          className="h-6 min-w-0 flex-1 border-0 bg-transparent p-0 text-[15px] text-[#121c15] shadow-none outline-none placeholder:text-[#617066] focus-visible:border-transparent focus-visible:ring-0"
          value={text}
          onChange={(event) => setText(event.target.value)}
          placeholder="Partilha uma dúvida ou uma dica…"
          aria-label="Nova publicação"
          aria-describedby={AJUDA_ID}
          maxLength={MAX_POST_LENGTH}
        />
        {/* O hit mínimo é o mesmo círculo verde da pílula; quando não dá para publicar, fica
            pálido mas o botão continua focável e a razão vai no texto de ajuda. */}
        <button
          type="submit"
          disabled={!ready}
          aria-label="Publicar"
          title={publishing ? 'A publicar…' : ready ? 'Publicar' : `Mínimo ${MIN_POST_LENGTH} caracteres`}
          aria-describedby={AJUDA_ID}
          className={cn('grid size-10 shrink-0 place-items-center rounded-full text-white transition-colors outline-none focus-visible:ring-[3px] focus-visible:ring-ring/40',
            ready ? 'bg-[#1f5a2c] hover:bg-[#1a4e26]' : 'bg-[#1f5a2c]/40')}
        >
          <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.4" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true"><path d="M12 5v14M5 12h14" /></svg>
        </button>
      </form>
      <span id={AJUDA_ID} className="sr-only">Mínimo {MIN_POST_LENGTH} caracteres. Máximo {MAX_POST_LENGTH} caracteres.</span>
      {text.length > 0 && (
        <p aria-hidden="true" className="pr-3 pt-1 text-right text-[11px] leading-4 text-[#617066]">{text.trim().length}/{MAX_POST_LENGTH}</p>
      )}
      {publishError && <Alert variant="destructive" className="mt-2">{publishError}</Alert>}
    </>
  );
}
