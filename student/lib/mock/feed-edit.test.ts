import test from 'node:test';
import assert from 'node:assert/strict';
import { deleteComment, deletePost, editComment, editPost, type EditablePost } from './feed-edit.ts';
import type { MockPostComment } from './feed-comments.ts';

const now = '2026-11-12T10:00:00';
const post = (extra: Partial<EditablePost> = {}): EditablePost => ({
  id: 1,
  authorAccountId: 7,
  type: 'doubt',
  title: null,
  content: 'Como se resolve uma equação?',
  isAutoGenerated: false,
  updatedAt: '2026-11-11T09:00:00',
  ...extra,
});
const comment = (extra: Partial<MockPostComment> = {}): MockPostComment => ({
  id: 5,
  postId: 1,
  authorAccountId: 7,
  content: 'Isola o x.',
  isHidden: false,
  createdAt: '2026-11-11T09:00:00',
  updatedAt: '2026-11-11T09:00:00',
  ...extra,
});

test('o autor edita o texto e a publicação fica marcada como editada', () => {
  const p = post();
  assert.deepEqual(editPost(p, 7, { content: '  Como se resolve uma equação do 1.º grau?  ' }, now), { ok: true });
  assert.equal(p.content, 'Como se resolve uma equação do 1.º grau?');
  assert.equal(p.updatedAt, now);
  assert.equal(p.edited, true);
});

test('quem não é o autor não edita, e uma publicação de simulação nunca se edita', () => {
  assert.equal(editPost(post(), 8, { content: 'Texto alheio' }, now).ok, false);
  const sim = editPost(post({ type: 'simulation' }), 7, { content: 'Outra coisa' }, now);
  assert.equal(sim.ok, false);
  assert.equal(sim.ok ? 0 : sim.status, 400);
  const auto = editPost(post({ isAutoGenerated: true }), 7, { content: 'Outra coisa' }, now);
  assert.equal(auto.ok, false);
});

test('o texto editado respeita os limites do compositor', () => {
  const p = post();
  assert.equal(editPost(p, 7, { content: 'oi' }, now).ok, false);
  assert.equal(editPost(p, 7, { content: 'a'.repeat(2001) }, now).ok, false);
  assert.equal(editPost(p, 7, { title: 'a'.repeat(151), content: 'Texto válido' }, now).ok, false);
  assert.equal(p.content, 'Como se resolve uma equação?');
});

test('os blocos editados substituem o conteúdo pelo resumo, como no compositor', () => {
  const p = post({ type: 'topic' });
  const done = editPost(p, 7, { title: 'Rede /28', blocks: [{ type: 'text', text: 'Numa /28 cabem 14 máquinas.' }] }, now);
  assert.deepEqual(done, { ok: true });
  assert.equal(p.title, 'Rede /28');
  assert.equal(p.content, 'Numa /28 cabem 14 máquinas.');
  assert.deepEqual(p.blocks, [{ type: 'text', text: 'Numa /28 cabem 14 máquinas.' }]);
});

test('uma publicação simples não aceita blocos', () => {
  const done = editPost(post({ type: 'doubt' }), 7, { blocks: [{ type: 'text', text: 'Bloco' }] }, now);
  // `doubt` é construída: aceita blocos. O que não aceita é um tipo que não existe no compositor.
  assert.equal(done.ok, true);
  const invalido = editPost(post({ type: 'exam' }), 7, { blocks: [{ type: 'text', text: 'Bloco' }] }, now);
  assert.equal(invalido.ok, false);
});

test('eliminar: o autor apaga a publicação e a conversa dela; outro aluno não', () => {
  const posts = [post()];
  const comments = [comment(), comment({ id: 6 })];
  assert.equal(deletePost(posts, comments, 1, 8, false).ok, false);
  assert.equal(posts.length, 1);
  assert.deepEqual(deletePost(posts, comments, 1, 7, false), { ok: true });
  assert.equal(posts.length, 0);
  assert.equal(comments.length, 0);
});

test('um moderador elimina a publicação de outra pessoa', () => {
  const posts = [post()];
  assert.deepEqual(deletePost(posts, [], 1, 99, true), { ok: true });
  assert.equal(posts.length, 0);
});

test('o autor edita o comentário; outro aluno não, e o texto tem limites', () => {
  const list = [comment()];
  const done = editComment(list, 1, 5, 7, '  Isola o x e divide por 2.  ', now);
  assert.equal(done.ok, true);
  assert.equal(list[0].content, 'Isola o x e divide por 2.');
  assert.equal(list[0].edited, true);
  assert.equal(editComment(list, 1, 5, 8, 'Outro texto', now).ok, false);
  assert.equal(editComment(list, 1, 5, 7, '   ', now).ok, false);
});

test('apagar um comentário acerta a contagem; uma resposta aceite recusa-se', () => {
  const p = { id: 1, commentCount: 2 };
  const comments = [comment(), comment({ id: 6, authorAccountId: 9, isAccepted: true })];
  const aceite = deleteComment(comments, p, 6, 9, false);
  assert.equal(aceite.ok, false);
  assert.equal(aceite.ok ? 0 : aceite.status, 409);

  p.commentCount = 2;
  assert.deepEqual(deleteComment(comments, p, 5, 7, false), { ok: true });
  assert.equal(p.commentCount, 1);
  assert.equal(comments.length, 1);
});
