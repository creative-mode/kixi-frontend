/** Editar e eliminar publicações e comentários em modo de demonstração (#753), sem
 *  servidor e sem React. Espelha as regras que o backend vai aplicar (creative-mode/kixi#593):
 *  só o autor edita; o autor ou um moderador elimina; uma resposta aceite não se apaga antes
 *  de a aceitação ser retirada. */

import { LIMITS, payloadOf, problemOf, summaryOf, type BuiltKind, type PostBlock } from '../post-blocks.ts';
import type { MockPostComment } from './feed-comments.ts';

export type EditError = { ok: false; status: number; message: string };

/** Os campos que uma publicação editável expõe ao mock; o `MockPost` do store encaixa aqui. */
export type EditablePost = {
  id: number;
  authorAccountId: number;
  type: string;
  title: string | null;
  content: string;
  isAutoGenerated: boolean;
  updatedAt: string;
  edited?: boolean;
  blocks?: PostBlock[];
};

const BUILT: readonly BuiltKind[] = ['doubt', 'topic', 'study_card', 'solution', 'challenge'];
const isBuilt = (type: string): type is BuiltKind => (BUILT as readonly string[]).includes(type);
const text = (value: unknown) => (typeof value === 'string' ? value : '');

/**
 * Edita uma publicação. O tipo não muda: quem edita corrige o que escreveu, não transforma
 * uma pergunta num desafio. Publicações de simulação e automáticas não se editam.
 */
export function editPost(post: EditablePost, accountId: number, body: Record<string, unknown>, now: string): { ok: true } | EditError {
  if (post.authorAccountId !== accountId) return { ok: false, status: 403, message: 'Só o autor pode editar a publicação' };
  if (post.isAutoGenerated || post.type === 'simulation') return { ok: false, status: 400, message: 'Esta publicação não pode ser editada' };

  const rawBlocks = body.blocks;
  if (rawBlocks !== undefined && (!Array.isArray(rawBlocks) || !isBuilt(post.type))) {
    return { ok: false, status: 400, message: 'Esta publicação não aceita blocos' };
  }
  const blocks = Array.isArray(rawBlocks) ? payloadOf(rawBlocks as PostBlock[]) : [];
  const title = text(body.title).trim();
  if (title.length > LIMITS.title) return { ok: false, status: 400, message: `O título tem no máximo ${LIMITS.title} caracteres` };

  const content = blocks.length > 0 ? summaryOf(blocks) : text(body.content).trim();
  if (blocks.length > 0) {
    const invalid = problemOf(post.type as BuiltKind, title, blocks);
    if (invalid) return { ok: false, status: 400, message: invalid };
  } else if (content.length < 5 || content.length > 2000) {
    return { ok: false, status: 400, message: 'O texto tem de ter entre 5 e 2000 caracteres' };
  }

  post.title = title || null;
  post.content = content;
  if (blocks.length > 0) post.blocks = blocks;
  else delete post.blocks;
  post.updatedAt = now;
  post.edited = true;
  return { ok: true };
}

/** Elimina uma publicação (e a conversa dela). Só o autor ou um moderador. */
export function deletePost(
  posts: EditablePost[],
  comments: MockPostComment[],
  postId: number,
  accountId: number,
  moderator: boolean,
): { ok: true } | EditError {
  const index = posts.findIndex((p) => p.id === postId);
  if (index < 0) return { ok: false, status: 404, message: 'Post not found' };
  const post = posts[index];
  if (post.authorAccountId !== accountId && !moderator) return { ok: false, status: 403, message: 'Só o autor ou um moderador pode eliminar a publicação' };
  posts.splice(index, 1);
  for (let i = comments.length - 1; i >= 0; i -= 1) if (comments[i].postId === postId) comments.splice(i, 1);
  return { ok: true };
}

/** Edita o texto de um comentário. Só o autor. */
export function editComment(
  comments: MockPostComment[],
  postId: number,
  commentId: number,
  accountId: number,
  content: string,
  now: string,
): { ok: true; comment: MockPostComment } | EditError {
  const comment = comments.find((c) => c.id === commentId && c.postId === postId);
  if (!comment || comment.isHidden) return { ok: false, status: 404, message: 'Comment not found' };
  if (comment.authorAccountId !== accountId) return { ok: false, status: 403, message: 'Só o autor pode editar o comentário' };
  const next = content.trim();
  if (next.length < 1 || next.length > 500) return { ok: false, status: 400, message: 'O comentário tem entre 1 e 500 caracteres' };
  comment.content = next;
  comment.updatedAt = now;
  comment.edited = true;
  return { ok: true, comment };
}

/**
 * Elimina um comentário e acerta a contagem da publicação. Só o autor ou um moderador.
 * Uma resposta já aceite recusa-se: primeiro retira-se a aceitação, para a pergunta não
 * ficar «resolvida» por uma resposta que já não existe.
 */
export function deleteComment(
  comments: MockPostComment[],
  post: { id: number; commentCount: number },
  commentId: number,
  accountId: number,
  moderator: boolean,
): { ok: true } | EditError {
  const index = comments.findIndex((c) => c.id === commentId && c.postId === post.id);
  if (index < 0 || comments[index].isHidden) return { ok: false, status: 404, message: 'Comment not found' };
  const comment = comments[index];
  if (comment.authorAccountId !== accountId && !moderator) return { ok: false, status: 403, message: 'Só o autor ou um moderador pode eliminar o comentário' };
  if (comment.isAccepted) return { ok: false, status: 409, message: 'Esta resposta foi aceite: retira a aceitação antes de a eliminar' };
  comments.splice(index, 1);
  post.commentCount = comments.filter((c) => c.postId === post.id && !c.isHidden).length;
  return { ok: true };
}
