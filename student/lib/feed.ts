import 'server-only';

import { apiGet, apiPost, type Result } from './api';
import { getPerson } from './profiles';
import type { FeedAuthor } from './feed-rules';

/** Os tipos que um aluno ou professor publica à mão; EXAM e MILESTONE são gerados
 *  pelo sistema e não aparecem aqui como opção de publicar. `simulation` é o cartão
 *  de uma prova simulada terminada, publicado a partir do resultado. */
export type PostType = 'doubt' | 'topic' | 'simulation';

/** O cartão de uma publicação `simulation`, tal como era quando foi publicada: os números
 *  e o nome da escola são lidos no servidor, nunca enviados pelo cliente. */
export interface SimulationCard {
  simulationId: number;
  statementTitle: string | null;
  schoolName: string | null;
  finalScore: number | null;
  maxScore: number | null;
  correctAnswers: number | null;
  totalQuestions: number | null;
  timeSpentSeconds: number | null;
}

export type ReactionType = 'applause' | 'strength';

/** GET /feed/posts (PostResponse). Sem nome do autor: o backend só devolve o id da
 *  conta. O nome e a foto resolvem-se à parte, pelo perfil público (`loadAuthors`). */
export interface FeedPost {
  id: number;
  authorAccountId: number;
  institutionId: number;
  schoolYearId: number;
  courseId: number;
  classId: number;
  type: string;
  title: string | null;
  content: string;
  isAutoGenerated: boolean;
  commentCount: number;
  hasReacted: boolean;
  createdAt: string;
  updatedAt: string;
  /** Só nas publicações do tipo `simulation`. */
  simulation?: SimulationCard | null;
}

export async function getFeed(classId: number, page = 1, limit = 10): Promise<Result<FeedPost[]>> {
  return apiGet<FeedPost[]>('/feed/posts', { classId, page, limit });
}

export async function createPost(
  classId: number,
  type: PostType,
  content: string,
  title?: string,
): Promise<Result<FeedPost>> {
  // O backend lê o enum pelo nome ('DOUBT'); as respostas é que trazem o valor em minúsculas.
  return apiPost<FeedPost>('/feed/posts', { type: type.toUpperCase(), classId, content, title: title || undefined });
}

/** Publica o resultado de uma simulação terminada, com uma reflexão opcional. */
export async function createSimulationPost(
  classId: number,
  simulationId: number,
  content: string,
): Promise<Result<FeedPost>> {
  return apiPost<FeedPost>('/feed/posts', { type: 'SIMULATION', classId, simulationId, content: content || undefined });
}

/** Alterna a reação do aluno (sempre 'applause' aqui: só há uma forma de aplaudir
 *  na interface, mesmo que o backend aceite 'strength' também). */
export async function toggleReaction(postId: number, reaction: ReactionType = 'applause') {
  return apiPost<{ reacted: boolean }>(`/feed/posts/${postId}/reactions`, { reaction: reaction.toUpperCase() });
}

/** Um comentário tal como o backend o devolve (#179). `displayName` vem já mascarado
 *  (primeiro nome e inicial do apelido) e é null quando a conta não tem perfil - um
 *  comentário não se perde por não haver nome para o mostrar. */
export interface PostComment {
  id: number;
  postId: number;
  authorAccountId: number;
  content: string;
  isHidden: boolean;
  createdAt: string;
  updatedAt: string;
  /** O backend diz se a linha é do aluno, para o cliente não comparar ids. */
  mine: boolean;
  displayName: string | null;
}

/** A conversa de uma publicação, do mais antigo para o mais novo (GET
 *  /feed/posts/{id}/comments). Um post de outra escola é 404, como o próprio post. */
export async function getComments(postId: number, page = 1, limit = 20): Promise<Result<PostComment[]>> {
  return apiGet<PostComment[]>(`/feed/posts/${postId}/comments`, { page, limit });
}

/** Escreve um comentário. A resposta é a linha completa — nome mascarado e `mine` —,
 *  para o painel a poder mostrar sem esperar por outra leitura. */
export async function addComment(postId: number, content: string) {
  return apiPost<PostComment>(`/feed/posts/${postId}/comments`, { content });
}

export async function reportPost(postId: number, reason: string) {
  return apiPost<{ id: number }>(`/feed/posts/${postId}/reports`, { reason });
}

/**
 * Resolve o nome e a foto de quem publicou, uma vez por conta (o mesmo autor em várias
 * publicações custa um só pedido). Um perfil que não responde fica de fora e a publicação
 * mostra "Colega": nunca um nome inventado. A própria conta não se pede, já se conhece.
 */
export async function loadAuthors(posts: FeedPost[], myAccountId: number | null): Promise<Record<number, FeedAuthor>> {
  const ids = [...new Set(posts.map((p) => p.authorAccountId))].filter((id) => id !== myAccountId);
  const found = await Promise.all(
    ids.map(async (id) => {
      const r = await getPerson(id).catch(() => null);
      return r?.ok && r.data.displayName?.trim()
        ? ([id, { name: r.data.displayName, photo: r.data.photo ?? null, verified: r.data.verified }] as const)
        : null;
    }),
  );
  return Object.fromEntries(found.filter((x): x is NonNullable<typeof x> => x != null));
}
